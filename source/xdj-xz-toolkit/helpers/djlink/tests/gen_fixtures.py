"""Writes tests/fixtures.h from the stock capture JSON.

The capture is stock XDJ-XZ traffic (keep-alives and beat packets) with the unit's MAC and LAN address replaced by
documentation values (00:00:5e:00:53:xx, 192.0.2.x)."""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
CAPTURE = HERE / "stock-passive-01.json"


def main() -> None:
    source = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else CAPTURE
    packets = json.loads(source.read_text(encoding="utf-8"))["packets"]
    lines = ["/* Generated by gen_fixtures.py from tests/" + source.name + "; do not edit. */",
             "struct fixture { unsigned port; unsigned len; uint8_t ip[4]; const uint8_t *bytes; };"]
    for i, p in enumerate(packets):
        data = bytes.fromhex(p["hex"])
        body = ",".join(f"0x{b:02x}" for b in data)
        lines.append(f"static const uint8_t fixture_{i}[] = {{{body}}};")
    lines.append("static const struct fixture fixtures[] = {")
    for i, p in enumerate(packets):
        ip = ",".join(p["src"].split("."))
        lines.append(f" {{{p['port']}, {len(bytes.fromhex(p['hex']))}, {{{ip}}}, fixture_{i}}},")
    lines.append("};")
    lines.append(f"#define FIXTURES {len(packets)}")
    (HERE / "fixtures.h").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
