"""Pack the owner's selected Wave Rider backgrounds as native RGB565 arrays."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path, help='Original BestOf2026zip folder; omit to repack retained crops')
args = parser.parse_args()
assets = root / 'wave-rider-assets'
assets.mkdir(exist_ok=True)
choices = [('liquid-wave', 'c626966c-792d-43a7-887a-1fba8d1496af', 76),
           ('sonic-tunnel', 'ccfbd5d1-5e55-449d-b433-9dac362241b0', 55),
           ('gold-phoenix', '962e793e-cf6a-496e-b1ac-b8c24ad72f1b', 65)]
catalog = []
if args.source:
    for name, identity, top in choices:
        found = list(args.source.glob('*' + identity + '.png'))
        if len(found) != 1:
            raise ValueError('Expected one original for ' + identity)
        original = found[0]
        digest = hashlib.sha256(original.read_bytes()).hexdigest()
        with Image.open(original) as image:
            width, height = image.size
            scaled = image.convert('RGB').resize((768, round(height * 768 / width)), Image.Resampling.LANCZOS)
            if top + 216 > scaled.height:
                raise ValueError('Selected crop exceeds source')
            scaled.crop((0, top, 768, top + 216)).save(assets / (name + '.png'))
        if hashlib.sha256(original.read_bytes()).hexdigest() != digest:
            raise RuntimeError('Original changed during packing')
        catalog.append({'name': name, 'original': str(original), 'sha256': digest,
                        'crop_top_after_width_768': top, 'original_unchanged': True})
    (assets / 'catalog.json').write_text(json.dumps({'artist': 'VJ OpticMystic', 'worlds': catalog}, indent=2) + '\n')
with (root / 'wave_rider_art.c').open('w', newline='\n') as output:
    output.write('/* Generated by pack_wave_rider_art.py; artwork by VJ OpticMystic. */\n#include "wave_rider_art.h"\n')
    output.write('const uint16_t xz_rider_background[3][XZ_RIDER_BG_W*XZ_RIDER_BG_H]={\n')
    for name, _, _ in choices:
        with Image.open(assets / (name + '.png')) as image:
            if image.size != (768, 216):
                raise ValueError('Unexpected panorama size')
            rgb = image.convert('RGB').tobytes()
            values = [((rgb[i] >> 3) << 11) | ((rgb[i+1] >> 2) << 5) | (rgb[i+2] >> 3)
                      for i in range(0, len(rgb), 3)]
        output.write('{\n')
        for i in range(0, len(values), 24):
            output.write(','.join(hex(v) for v in values[i:i+24]) + ',\n')
        output.write('},\n')
    output.write('};\n')
print('Packed three owner-art worlds; originals unchanged')
