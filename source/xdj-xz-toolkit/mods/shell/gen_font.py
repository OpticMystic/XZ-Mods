"""Build the shell's large numeral faces from the same OFL font as ../ui/fonts.

The MODS atlas stops at a 14 px cap height. The play screen's time and BPM
read at 20-28 px, and doubling the small face looks coarse, so three extra
faces are rasterised here for the characters a readout can contain.
"""
from pathlib import Path
import hashlib
import json
import math
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent
fonts = root.parent / 'ui' / 'fonts'
source = fonts / 'BarlowSemiCondensed-Medium.ttf'
manifest = json.loads((fonts / 'source.json').read_text())
if hashlib.sha256(source.read_bytes()).hexdigest() != manifest['sha256'][source.name]:
    raise ValueError('Font source differs from its pinned digest')
CHARSET = '0123456789:.-+%± '
FACES = (('MID', 28), ('BPM', 34), ('BIG', 40))
data = []
lines = ['/* Generated by shell/gen_font.py. Glyph data: SIL-OFL-1.1; see ../ui/fonts/OFL.txt. */',
         '#ifndef XZ_SHELL_FONT_H', '#define XZ_SHELL_FONT_H', '#include <stdint.h>',
         'struct xz_shell_glyph { uint32_t offset; uint8_t width,height; int8_t x,y; uint8_t advance; };',
         '#define XZ_SHELL_FONT_CHARSET "' + CHARSET.replace('±', '\\xb1') + '"',
         '#define XZ_SHELL_FONT_GLYPHS %d' % len(CHARSET)]
for name, size in FACES:
    font = ImageFont.truetype(str(source), size)
    baseline = -font.getbbox('H', anchor='ls')[1]
    glyphs = []
    for char in CHARSET:
        x0, y0, x1, y1 = font.getbbox(char, anchor='ls')
        width, height = x1 - x0, y1 - y0
        mask = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(mask).text((-x0, -y0), char, font=font, anchor='ls', fill=255)
        pixels = list(mask.tobytes()) if width and height else []
        glyphs.append((len(data), width, height, x0, y0 + baseline, math.ceil(font.getlength(char))))
        data.extend(pixels)
    lines.append('#define XZ_SHELL_FONT_%s_CAP %d' % (name, baseline))
    lines.append('static const struct xz_shell_glyph xz_shell_font_%s[XZ_SHELL_FONT_GLYPHS] = {' % name.lower())
    lines.extend('{' + ','.join(map(str, g)) + '},' for g in glyphs)
    lines.append('};')
lines.append('static const unsigned char xz_shell_font_coverage[] = {')
for i in range(0, len(data), 32):
    lines.append(','.join(map(str, data[i:i + 32])) + ',')
lines.extend(['};', '#endif', ''])
(root / 'shell_font.h').write_text('\n'.join(lines), encoding='ascii')
print(f'Generated {len(FACES)} numeral faces, {len(data)} coverage bytes')
