"""Generate dj_name_key_table.h (the NFC tables behind dj_name_key.c) from Python's unicodedata.

Run with the newest Python available; the header records which Unicode version it was built from.
tests/verify_dj_name_key.py imports render() to check the checked-in header is current."""
from pathlib import Path
import unicodedata

HEADER = Path(__file__).resolve().parent/'dj_name_key_table.h'
HANGUL = range(0xAC00, 0xAC00+11172)


def tables():
    decomp = {}
    for cp in range(0x110000):
        if cp in HANGUL:
            continue
        mapping = unicodedata.decomposition(chr(cp))
        if mapping and not mapping.startswith('<'):
            parts = [int(x, 16) for x in mapping.split()]
            assert 1 <= len(parts) <= 2 and 0 not in parts, hex(cp)
            decomp[cp] = parts
    entries = sorted(decomp)
    index = {cp: i for i, cp in enumerate(entries)}
    composes = sorted((tuple(decomp[c]), index[c]) for c in entries
                      if len(decomp[c]) == 2 and unicodedata.normalize('NFC', chr(c)) == chr(c))
    ranges = []
    for cp in range(0x110000):
        ccc = unicodedata.combining(chr(cp))
        if not ccc:
            continue
        if ranges and ranges[-1][0]+ranges[-1][1] == cp and ranges[-1][2] == ccc and ranges[-1][1] < 2048:
            ranges[-1][1] += 1
        else:
            ranges.append([cp, 1, ccc])
    return decomp, entries, composes, ranges


def check(decomp, entries, composes):
    """Assert the properties dj_name_key.c relies on, so a future Unicode version that breaks one fails here."""
    def full(cp, depth=0):
        assert depth < 8
        return [x for part in decomp[cp] for x in full(part, depth+1)] if cp in decomp else [cp]
    ratio = 1
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        nfd = unicodedata.normalize('NFD', chr(cp))
        if cp not in HANGUL:
            assert ''.join(map(chr, full(cp))) == nfd, hex(cp)
        width = len(chr(cp).encode())
        assert len(nfd.encode()) <= 3*width, hex(cp)
        ratio = max(ratio, -(-len(nfd)//width))
    assert min(cp for cp in decomp if cp not in HANGUL) >= 0xC0
    assert all(unicodedata.combining(chr(cp)) == 0 for cp in range(0x300)) and unicodedata.combining(chr(0x300))
    for (a, b), i in composes:
        c = entries[i]
        assert unicodedata.combining(chr(a)) == 0 and unicodedata.combining(chr(c)) == 0, hex(c)
        assert len(chr(c).encode()) <= len(chr(a).encode())+len(chr(b).encode()), hex(c)
        assert b >= 0x300 and a < 0x110000, hex(c)
    return ratio


def render():
    decomp, entries, composes, ranges = tables()
    ratio = check(decomp, entries, composes)
    assert len(entries) < 65536
    version = unicodedata.unidata_version
    lines = ['/* SPDX-License-Identifier: MIT */',
             f'/* Generated by gen_dj_name_key.py from Python unicodedata (unidata_version {version}). Do not edit. */',
             '#ifndef XZ_DJ_NAME_KEY_TABLE_H', '#define XZ_DJ_NAME_KEY_TABLE_H', '#include <stdint.h>',
             f'#define XZ_DJ_NAME_KEY_UNICODE "{version}"',
             f'#define XZ_DJ_NAME_KEY_DECOMP_PER_BYTE {ratio} /* canonical decomposition code points per UTF-8 byte, at most */',
             f'/* Canonical decomposition mappings, cp<<42|first<<21|second (second 0 for singletons), sorted. {len(entries)} entries. */',
             'static const uint64_t xz_dj_decomp[] = {']
    words = [f'0x{cp<<42|decomp[cp][0]<<21|(decomp[cp][1] if len(decomp[cp]) == 2 else 0):x}' for cp in entries]
    lines += wrap(words)
    lines += [f'/* Primary composites: indices into xz_dj_decomp sorted by (first, second). {len(composes)} entries. */',
              'static const uint16_t xz_dj_compose[] = {']
    lines += wrap(str(i) for _, i in composes)
    lines += [f'/* Nonzero canonical combining classes: start<<11|(length-1), sorted, and the class of each run. {len(ranges)} runs. */',
              'static const uint32_t xz_dj_ccc_run[] = {']
    lines += wrap(f'0x{start<<11|(length-1):x}' for start, length, _ in ranges)
    lines += ['static const uint8_t xz_dj_ccc_class[] = {']
    lines += wrap(str(ccc) for _, _, ccc in ranges)
    lines += ['#endif', '']
    sizes = {'decomp': 8*len(entries), 'compose': 2*len(composes), 'ccc': 5*len(ranges)}
    return '\n'.join(lines), sizes


def wrap(words, width=118):
    out, line = [], ''
    for word in words:
        if line and len(line)+len(word)+1 > width:
            out.append(line)
            line = ''
        line += word+','
    return out+[line, '};']


if __name__ == '__main__':
    text, sizes = render()
    HEADER.write_bytes(text.encode('ascii'))
    print(f'wrote {HEADER.name} (Unicode {unicodedata.unidata_version}); rodata bytes:',
          ', '.join(f'{k} {v}' for k, v in sizes.items()), f'= {sum(sizes.values())}')
