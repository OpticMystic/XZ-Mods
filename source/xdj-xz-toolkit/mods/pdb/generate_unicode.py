"""Regenerate the C Unicode default-casefold table from Python's Unicode data."""
from pathlib import Path
import unicodedata

def main():
    rows = []
    for point in range(0x110000):
        folded = tuple(map(ord, chr(point).casefold()))
        if folded != (point,):
            assert 1 <= len(folded) <= 3
            values = (*folded, *(0 for _ in range(3 - len(folded))))
            rows.append("    {%su, {%s}, %d}," % (hex(point), ", ".join(hex(x) + "u" for x in values), len(folded)))
    text = ("/* SPDX-License-Identifier: MIT\n * Generated by generate_unicode.py; Unicode " + unicodedata.unidata_version + ". */\n"
            "struct fold_map { uint32_t from, to[3]; unsigned char count; };\n"
            "static const struct fold_map fold_table[] = {\n" + "\n".join(rows) + "\n};\n")
    Path(__file__).with_name("unicode_fold.h").write_text(text, encoding="ascii")

if __name__ == "__main__":
    main()
