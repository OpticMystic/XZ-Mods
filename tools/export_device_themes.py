"""Write ui/device-themes.js from the native theme table so the desktop settings menu shows the XZ's real palettes."""
import json,re,sys
from pathlib import Path

APP=Path(__file__).resolve().parents[1]
mods=Path(sys.argv[1]) if len(sys.argv)>1 else APP.parent/'VJToolsLibrary/packages/xdj-xz-toolkit/mods'
ui=mods/'ui'
macros={}
for header in ui.glob('theme_*.h'):
    text=header.read_text(encoding='utf-8')
    for name,value in re.findall(r'#define (XZ_THEME_\w+) (.+)',text):macros[name]=value.strip()
source=ui.joinpath('themes.h').read_text(encoding='utf-8')
table=source[source.index('static const struct xz_theme table'):]
themes=[]
for line in table.splitlines():
    line=line.strip()
    if not line.startswith('{"') and not line.startswith('{XZ_THEME_'):continue
    for name,value in macros.items():line=line.replace(name,value)
    label=re.match(r'\{"([^"]+)"',line).group(1)
    colors=[int(x,16) for x in re.findall(r'0x([0-9a-fA-F]{6})',line)[:7]]
    if len(colors)<7:raise SystemExit('Palette missing for '+label)
    dark=int(line.split(',')[2])
    themes.append({'label':label,'dark':dark==1,'bg':colors[0],'ink':colors[1],'accent':colors[2],'alarm':colors[3],'stems':colors[4:7]})
if len(themes)!=25:raise SystemExit('Expected 25 themes, parsed '+str(len(themes)))
hexes=lambda value:'#%06x'%value
out=[{**theme,'bg':hexes(theme['bg']),'ink':hexes(theme['ink']),'accent':hexes(theme['accent']),'alarm':hexes(theme['alarm']),'stems':[hexes(c) for c in theme['stems']]} for theme in themes]
(APP/'ui/device-themes.js').write_text('// Generated by tools/export_device_themes.py from mods/ui/themes.h. Do not edit by hand.\nconst DEVICE_THEMES='+json.dumps(out,separators=(',',':'))+';\n',encoding='utf-8',newline='\n')
print('wrote',len(out),'themes')
