"""Generate shared support values. --check fails on byte or consumer drift."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def ts_type(schema):
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(s) for s in schema['anyOf'])
    kind = schema['type']
    if kind == 'object':
        return '{ ' + '; '.join(json.dumps(k) + ('' if k in schema['required'] else '?') + ': ' + ts_type(v)
                               for k, v in schema['properties'].items()) + ' }'
    if kind == 'array':
        return 'Array<' + ts_type(schema['items']) + '>'
    return {'string':'string', 'integer':'number', 'boolean':'boolean', 'null':'null'}[kind]

def outputs():
    contract = json.loads((ROOT / 'spec/support-contract.json').read_text())
    sources = json.loads((ROOT / 'spec/support-sources.json').read_text())
    encoded = json.dumps({'contract':contract, 'sources':sources}, separators=(',', ':'), ensure_ascii=True)
    digest = hashlib.sha256(encoded.encode()).hexdigest()
    stamp = '// Generated by tools/generate_support_contract.py; do not edit.\n'
    ts = stamp + 'export const CONTRACT = ' + json.dumps(contract, indent=2) + ' as const;\n'
    ts += 'export const SOURCES = ' + json.dumps(sources, indent=2) + ' as const;\n'
    ts += 'export type ReportV2 = ' + ts_type(contract['report_schema']) + ';\n'
    ts += 'export type ReportKind = typeof CONTRACT.kinds[number];\n'
    ts += 'export type Lifecycle = typeof CONTRACT.lifecycles[number];\n'
    ts += 'export type Outcome = typeof CONTRACT.outcomes[number];\n'
    ts += 'export type StatusTextKey = keyof typeof CONTRACT.status_text;\n'
    yield 'services/support/src/contract.generated.ts', ts
    yield 'source/xdj-xz-toolkit/builder/support_contract.py', (
        '# Generated by tools/generate_support_contract.py; do not edit.\nimport json\n'
        + '_DATA = json.loads(' + repr(encoded) + ')\nCONTRACT = _DATA["contract"]\nSOURCES = _DATA["sources"]\n')
    yield 'spec/generated/support-contract.mjs', stamp + 'export const {contract, sources} = ' + encoded + ';\n'
    yield 'spec/generated/support_contract.rs', (
        stamp + '// Phase 3 includes this module; JSON is the authoritative wire schema.\n'
        + 'pub const CONTRACT_JSON: &str = include_str!("../support-contract.json");\n'
        + 'pub const SOURCES_JSON: &str = include_str!("../support-sources.json");\n'
        + f'pub const CONTRACT_SHA256: &str = "{digest}";\n'
        + ''.join(f'pub const {k.upper()}: usize = {v};\n' for k,v in contract['limits'].items())
        + 'pub const REPORT_KINDS: &[&str] = &[' + ','.join(json.dumps(v) for v in contract['kinds']) + '];\n')

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for relative, content in outputs():
        path = ROOT / relative
        expected = content.encode()
        if args.check:
            if not path.exists() or path.read_bytes().replace(b'\r\n', b'\n') != expected:
                bad.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    # The v1 transport is deliberately unchanged until phase 3. Its common cap
    # must still match the contract. New consumers import the generated modules.
    cap = json.loads((ROOT / 'spec/support-contract.json').read_text())['limits']['report_bytes']
    rust = (ROOT / 'src-tauri/src/support.rs').read_text()
    if not re.search(r'const CAP:usize=' + str(cap) + r';', rust):
        bad.append('src-tauri/src/support.rs: v1 transport cap')
    if bad:
        raise SystemExit('Support contract drift: ' + ', '.join(bad))
    print('Support contracts match all generated consumers and the v1 transport cap.')

if __name__ == '__main__':
    main()
