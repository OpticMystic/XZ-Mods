ROOT = Path(__file__).resolve().parents[1]

def ts_type(schema):
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(s) for s in schema['anyOf'])
    kind = schema['type']
    if kind == 'object':
        return '{ ' + '; '.join(json.dumps(k) + ('' if k in schema['required'] else '?') + ': ' + ts_type(v)
                               for k, v in schema['properties'].items()) + ' }'
    if kind == 'array':
        return 'Array<' + ts_type(schema['items']) + '>'
    return {'string':'string', 'integer':'number', 'boolean':'boolean', 'null':'null'}[kind]

