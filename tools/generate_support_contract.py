"""Generate shared support values. --check fails on byte or consumer drift."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def ts_type(schema):
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(s) for s in schema['anyOf'])
    kind = schema['type']
    if kind == 'object':
        return '{ ' + '; '.join(json.dumps(k) + ('' if k in schema['required'] else '?') + ': ' + ts_type(v)
                               for k, v in schema['properties'].items()) + ' }'
    if kind == 'array':
        return 'Array<' + ts_type(schema['items']) + '>'
    return {'string':'string', 'integer':'number', 'boolean':'boolean', 'null':'null'}[kind]

def outputs():
    contract = json.loads((ROOT / 'spec/support-contract.json').read_text())
    sources = json.loads((ROOT / 'spec/support-sources.json').read_text())
    encoded = json.dumps({'contract':contract, 'sources':sources}, separators=(',', ':'), ensure_ascii=True)
    digest = hashlib.sha256(encoded.encode()).hexdigest()
    stamp = '// Generated by tools/generate_support_contract.py; do not edit.\n'
    ts = stamp + 'export const CONTRACT = ' + json.dumps(contract, indent=2) + ' as const;\n'
    ts += 'export const SOURCES = ' + json.dumps(sources, indent=2) + ' as const;\n'
    ts += 'export type ReportV2 = ' + ts_type(contract['report_schema']) + ';\n'
    ts += 'export type ReportKind = typeof CONTRACT.kinds[number];\n'
    ts += 'export type Lifecycle = typeof CONTRACT.lifecycles[number];\n'
    ts += 'export type Outcome = typeof CONTRACT.outcomes[number];\n'
    ts += 'export type StatusTextKey = keyof typeof CONTRACT.status_text;\n'
    ts += 'export type DeskFields = ' + ts_type(contract['desk_schema']) + ';\n'
    ts += '''export function automaticFixEligible(kind: string | null, impact: string | null): boolean {
  return CONTRACT.automatic_fix.kinds.some(k => k === kind) && CONTRACT.automatic_fix.impacts.some(i => i === impact);
}
export function inboxPriority(kind: string | null, impact: string | null, expectation: string | null, severity: string | null): number {
  if ((kind === 'REGRESSION' || kind === 'DEGRADATION') && severity === 'LIVE_SET_STOPPER') return 0;
  if (impact === 'RESTORES_EXPECTED') {
    if (expectation === 'STOCK_XZ') return 1;
    if (expectation === 'XZ_CONSISTENCY') return 2;
    if (expectation === 'DJ_CONVENTION') return 3;
  }
  if (CONTRACT.automatic_fix.kinds.some(k => k === kind)) return 4;
  if (kind === 'FEATURE' && impact === 'ADDITIVE') return 5;
  return 6;
}
'''
    yield 'services/support/src/contract.generated.ts', ts
    yield 'source/xdj-xz-toolkit/builder/support_contract.py', (
        '# Generated by tools/generate_support_contract.py; do not edit.\nimport json\n'
        + '_DATA = json.loads(' + repr(encoded) + ')\nCONTRACT = _DATA["contract"]\nSOURCES = _DATA["sources"]\n'
        + "\ndef automatic_fix_eligible(kind, impact):\n    return kind in CONTRACT['automatic_fix']['kinds'] and impact in CONTRACT['automatic_fix']['impacts']\n")
    yield 'spec/generated/support-contract.mjs', stamp + 'export const {contract, sources} = ' + encoded + ';\n' + (
        'export const automaticFixEligible = (kind, impact) => contract.automatic_fix.kinds.includes(kind) && contract.automatic_fix.impacts.includes(impact);\n')
    yield 'spec/generated/support_contract.rs', (
        stamp + '// Phase 3 includes this module; JSON is the authoritative wire schema.\n'
        + 'pub const CONTRACT_JSON: &str = include_str!("../support-contract.json");\n'
        + 'pub const SOURCES_JSON: &str = include_str!("../support-sources.json");\n'
        + f'pub const CONTRACT_SHA256: &str = "{digest}";\n'
        + ''.join(f'pub const {k.upper()}: usize = {v};\n' for k,v in contract['limits'].items())
        + 'pub const REPORT_KINDS: &[&str] = &[' + ','.join(json.dumps(v) for v in contract['kinds']) + '];\n'
        + 'pub fn automatic_fix_eligible(kind: &str, impact: &str) -> bool {\n    matches!(kind, '
        + ' | '.join(json.dumps(v) for v in contract['automatic_fix']['kinds']) + ') && matches!(impact, '
        + ' | '.join(json.dumps(v) for v in contract['automatic_fix']['impacts']) + ')\n}\n')
    config = json.loads((ROOT / 'services/support/wrangler.jsonc').read_text())
    bindings = [(b['binding'], 'D1Database') for b in config['d1_databases']]
    bindings += [(b['binding'], 'R2Bucket') for b in config['r2_buckets']]
    bindings += [(name, 'string') for name in config['vars']]
    yield 'services/support/worker-configuration.d.ts', (
        stamp + '// Offline generation reads config only, never local secrets or credentials.\n'
        + 'declare namespace Cloudflare {\n  interface Env {\n'
        + ''.join(f'    {name}: {kind};\n' for name, kind in bindings)
        + '  }\n}\n')

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for relative, content in outputs():
        path = ROOT / relative
        expected = content.encode()
        if args.check:
            if not path.exists() or path.read_bytes().replace(b'\r\n', b'\n') != expected:
                bad.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.exists() and b'\r\n' in path.read_bytes():
                expected = expected.replace(b'\n', b'\r\n')
            path.write_bytes(expected)
    # The desktop transport imports its cap from the generated module, never a literal.
    rust = (ROOT / 'src-tauri/src/support.rs').read_text()
    if not re.search(r'const CAP:usize=crate::support_contract::REPORT_BYTES;', rust):
        bad.append('src-tauri/src/support.rs: transport cap')
    main = (ROOT / 'src-tauri/src/main.rs').read_text()
    if '#[path="../../spec/generated/support_contract.rs"]' not in main:
        bad.append('src-tauri/src/main.rs: generated contract module')
    migration = ROOT / 'services/support/migrations/0002_bugdesk_tracking.sql'
    if migration.exists():
        contract = json.loads((ROOT / 'spec/support-contract.json').read_text())
        expected = {'kind': 'kinds', 'classified_kind': 'kinds', 'previous_kind': 'kinds',
                    'new_kind': 'kinds', 'kind_hint': 'kind_hints', 'expectation': 'expectations',
                    'impact': 'impacts', 'severity': 'severities', 'outcome': 'outcomes'}
        for field, values in re.findall(r'CHECK\((\w+) IN \(([^)]+)\)\)', migration.read_text()):
            if field in expected and set(re.findall(r"'([^']+)'", values)) != set(contract[expected[field]]):
                bad.append('0002_bugdesk_tracking.sql: ' + field)
    if bad:
        raise SystemExit('Support contract drift: ' + ', '.join(bad))
    print('Support contracts match all generated consumers and the desktop transport cap.')

if __name__ == '__main__':
    main()
