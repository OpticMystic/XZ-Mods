"""Write ui/mod-changes.js: for each XZ Mods build, the ids of the changes its source contains.

A change belongs to a build when the change's commit is an ancestor of the build's source commit in the
VJToolsLibrary monorepo. The app's update preview is then a set difference between two builds.
"""
import argparse,json,re,subprocess,sys
from pathlib import Path

APP=Path(__file__).resolve().parents[1]
KINDS={'new','improved','fixed'}
SHA=re.compile(r'^[0-9a-f]{7,40}$')

def git(monorepo,*args):
    return subprocess.run(['git','-C',str(monorepo),*args],capture_output=True,text=True)

def resolve(monorepo,sha,what):
    if not SHA.match(str(sha).lower()):raise SystemExit(f'{what}: {sha!r} is not a commit sha')
    out=git(monorepo,'rev-parse','--verify','--quiet',str(sha)+'^{commit}')
    if out.returncode:raise SystemExit(f'{what}: commit {sha} does not resolve in {monorepo}')
    return out.stdout.strip()

def contains(monorepo,change,build):
    out=git(monorepo,'merge-base','--is-ancestor',change,build)
    if out.returncode in (0,1):return out.returncode==0
    raise SystemExit(f'git merge-base failed for {change} in {build}: {out.stderr.strip()}')

def commit_time(monorepo,sha):
    return int(git(monorepo,'show','-s','--format=%ct',sha).stdout.strip())

def bundled_build(runtime_manifest):
    if not runtime_manifest.is_file():return None
    sha=json.loads(runtime_manifest.read_text(encoding='utf-8')).get('source_commit')
    return sha if sha and SHA.match(str(sha).lower()) else None

def export(data,monorepo,runtime_manifest):
    if data.get('format')!='xz-mod-changes/1':raise SystemExit('Expected format xz-mod-changes/1, got '+repr(data.get('format')))
    changes={}
    for change in data['changes']:
        if change['id'] in changes:raise SystemExit('Duplicate change id '+change['id'])
        if change['kind'] not in KINDS:raise SystemExit(f"Change {change['id']}: unknown kind {change['kind']!r}")
        changes[change['id']]={**change,'commit':resolve(monorepo,change['commit'],'change '+change['id'])}
    builds={resolve(monorepo,build['source_commit'],'build '+build.get('label','')) for build in data['builds']}
    bundled=bundled_build(runtime_manifest)
    if bundled:builds.add(resolve(monorepo,bundled,'bundled runtime'))
    when={sha:commit_time(monorepo,sha) for sha in {change['commit'] for change in changes.values()}}
    newest=sorted(changes.values(),key=lambda change:(-when[change['commit']],change['id']))
    return {'format':'xz-mod-changes-ui/1',
        'changes':{change['id']:{'kind':change['kind'],'area':change['area'],'text':change['text']} for change in newest},
        'builds':{build:[change['id'] for change in newest if contains(monorepo,change['commit'],build)] for build in sorted(builds)}}

def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--input',type=Path,default=APP/'mod-changes.json')
    parser.add_argument('--monorepo',type=Path,default=APP.parent/'VJToolsLibrary')
    parser.add_argument('--runtime-manifest',type=Path,default=APP/'resources/runtime/manifest.json')
    parser.add_argument('--output',type=Path,default=APP/'ui/mod-changes.js')
    args=parser.parse_args(argv)
    result=export(json.loads(args.input.read_text(encoding='utf-8')),args.monorepo,args.runtime_manifest)
    header='// Generated by tools/export_mod_changes.py from '+args.input.name+' and the VJToolsLibrary history. Do not edit by hand.\n'
    args.output.write_text(header+'window.MOD_CHANGES='+json.dumps(result,sort_keys=True,separators=(',',':'),ensure_ascii=False)+';\n',encoding='utf-8',newline='\n')
    print('wrote',len(result['changes']),'changes across',len(result['builds']),'builds to',args.output)

if __name__=='__main__':main()
